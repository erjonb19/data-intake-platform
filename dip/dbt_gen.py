"""dbt models generated from a data contract (Stage 10, S10.3; PLAN.md section 8.12).

    python -m dip contracts dbt FEED [--write]

The contract is the single source of truth: the SQL comes from templates here, never from
a model. For a CSV or Excel feed (both land in bronze.csv_record):

  silver  <pack>_<name>_record: one row per accepted row, every contract column typed by
          its contract type, with the delivery columns every hand-written file-feed model
          has (file_sha256, row_number, source_key, file_date, received_at,
          contract_version) and the same `deliveries` CTE. The intake already checked each
          value, and optional columns go through nullif(..., ''), so the casts cannot fail.
  tests   _<pack>_<name>.yml: (file_sha256, row_number) unique; not_null for required
          columns; accepted_values for `allowed`; a `unique: true` column unique within
          its file (the contract checks it per file).
  gold    <pack>_<name>: only when the contract has a `model:` block. `grain:
          latest_per_key` with `key: [...]` keeps the newest row per key (by file date,
          then receipt); `grain: all_rows` keeps every row as a table.

Files go under dbt/models/<pack>/<name>/ and start with GENERATED; the generator rewrites
only files that do. Feeds whose models are hand-written (any model tagged with the feed
that is not generated: eligibility, claims, finance, X12) get no generated files. For them,
`affected_models` lists the hand-written models that read a column a candidate contract
removes or renames, for a person to fix.
"""

from __future__ import annotations

import hashlib
import re
from pathlib import Path
from typing import Any

from dip.contracts import REPO_ROOT, Contract

DBT_MODELS = REPO_ROOT / "dbt" / "models"
GENERATED = "generated by dip from"
FORMATS = ("csv", "excel")
CASTS = {"integer": "bigint", "decimal": "numeric", "date": "date", "boolean": "boolean"}


class GenerationError(ValueError):
    pass


def names(feed: str) -> tuple[str, str, str]:
    """(pack, name, model prefix) for a feed `<pack>.<name>`."""
    pack, _, name = feed.partition(".")
    return pack, name, f"{pack}_{name}"


def paths(feed: str) -> dict[str, str]:
    """Repo-relative paths of the generated files, by role."""
    pack, name, prefix = names(feed)
    base = f"dbt/models/{pack}/{name}"
    return {"silver": f"{base}/{prefix}_record.sql", "tests": f"{base}/_{prefix}.yml",
            "gold": f"{base}/{prefix}.sql"}  # fmt: skip


def _header(c: Contract, comment: str) -> str:
    return (f"{comment} {GENERATED} the {c.feed} contract, version {c.version}. Do not edit:"
            f" change the contract, then\n{comment} python -m dip contracts dbt {c.feed}"
            " --write\n")  # fmt: skip


def _column(col: dict[str, Any]) -> str:
    name, kind = col["name"], col.get("type", "string")
    raw = f"b.record ->> '{name}'"
    value = raw if col.get("required") else f"nullif({raw}, '')"
    if kind in CASTS:
        value = f"({value})::{CASTS[kind]}"
    return f'    {value} as "{name}"'


def _silver(c: Contract) -> str:
    feed = c.feed
    cols = ",\n".join(_column(col) for col in c.spec["columns"])
    return (
        _header(c, "--")
        + "{{ config(schema='silver', materialized='view', tags=['file_feed', '"
        + feed
        + "', 'generated']) }}\n\n"
        f"""-- Silver: every accepted row of every {feed} file, typed by the contract.
with deliveries as (
    select distinct on (d.file_sha256)
        d.file_sha256,
        d.source_key,
        coalesce(d.file_date, (d.received_at at time zone 'UTC')::date) as file_date,
        d.received_at
    from {{{{ source('ops', 'intake_delivery') }}}} as d
    where d.feed = '{feed}'
    order by
        d.file_sha256,
        coalesce(d.file_date, (d.received_at at time zone 'UTC')::date) desc,
        d.received_at desc,
        d.source_key desc
)

select
    b.file_sha256,
    b.row_number,
    d.source_key,
    d.file_date,
    d.received_at,
    f.contract_version,
{cols}
from {{{{ source('bronze', 'csv_record') }}}} as b
inner join {{{{ source('ops', 'intake_file') }}}} as f
    on f.feed = b.feed and f.file_sha256 = b.file_sha256
inner join deliveries as d on d.file_sha256 = b.file_sha256
where b.feed = '{feed}'
"""
    )


def _gold(c: Contract, model: dict[str, Any]) -> str:
    _, _, prefix = names(c.feed)
    head = (_header(c, "--") + "{{ config(schema='gold', materialized='table', tags=["
            f"'file_feed', '{c.feed}', 'generated']) }}}}\n\n")  # fmt: skip
    if model["grain"] == "all_rows":
        return head + (f"-- Gold: every accepted {c.feed} row (grain: all_rows).\n"
                       f"select * from {{{{ ref('{prefix}_record') }}}}\n")  # fmt: skip
    key = ", ".join(f'r."{k}"' for k in model["key"])
    return head + (
        f"-- Gold: the newest row per {', '.join(model['key'])} (grain: latest_per_key), by\n"
        "-- the file's business date, then when it was received.\n"
        f"select distinct on ({key}) r.*\n"
        f"from {{{{ ref('{prefix}_record') }}}} as r\n"
        f"order by {key}, r.file_date desc, r.received_at desc, r.file_sha256 desc,"
        " r.row_number desc\n"
    )


def _tests(c: Contract, model: dict[str, Any] | None) -> str:
    _, _, prefix = names(c.feed)
    lines = [_header(c, "#").rstrip("\n"), "version: 2", "", "models:",
             f"  - name: {prefix}_record", "    data_tests:", "      - unique_combination:",
             "          arguments: {columns: [file_sha256, row_number]}"]  # fmt: skip
    unique = [col["name"] for col in c.spec["columns"] if col.get("unique")]
    for u in unique:
        lines += ["      - unique_combination:",
                  f"          arguments: {{columns: [file_sha256, {u}]}}"]  # fmt: skip
    cols = []
    for col in c.spec["columns"]:
        tests = []
        if col.get("required"):
            tests.append("not_null")
        if col.get("allowed") and col.get("type", "string") == "string":
            values = ", ".join(_yaml_str(v) for v in col["allowed"])
            tests.append(f"accepted_values: {{arguments: {{values: [{values}]}}}}")
        if tests:
            cols += [f"      - name: {col['name']}", "        data_tests:"]
            cols += [f"          - {t}" for t in tests]
    if cols:
        lines += ["    columns:", *cols]
    if model and model["grain"] == "latest_per_key":
        keys = ", ".join(model["key"])
        lines += [f"  - name: {prefix}", "    data_tests:", "      - unique_combination:",
                  f"          arguments: {{columns: [{keys}]}}"]  # fmt: skip
    return "\n".join(lines) + "\n"


def _yaml_str(v: Any) -> str:
    s = str(v).replace("\\", "\\\\").replace('"', '\\"')
    return f'"{s}"'


def render(c: Contract) -> dict[str, str]:
    """The generated files for a contract, as {repo-relative path: text}."""
    if c.format_type not in FORMATS:
        raise GenerationError(f"{c.feed}: no generator for format {c.format_type!r}")
    model = c.spec.get("model")
    p = paths(c.feed)
    out = {p["silver"]: _silver(c), p["tests"]: _tests(c, model)}
    if model:
        out[p["gold"]] = _gold(c, model)
    return out


def files_sha256(files: dict[str, str]) -> str:
    """One hash over the files and their paths: what a person approved."""
    h = hashlib.sha256()
    for path in sorted(files):
        h.update(path.encode() + b"\0" + files[path].encode() + b"\0")
    return h.hexdigest()


def _is_generated(path: Path) -> bool:
    try:
        head = path.read_text(encoding="utf-8")[:300]
    except OSError:
        return False
    return GENERATED in head


def hand_written(feed: str, models: Path = DBT_MODELS) -> list[Path]:
    """Hand-written models tagged with the feed (its own silver, gold and anything else)."""
    tag = re.compile(r"tags\s*=\s*\[[^\]]*'" + re.escape(feed) + "'")
    return sorted(
        p
        for p in models.rglob("*.sql")
        if not _is_generated(p) and tag.search(p.read_text(encoding="utf-8"))
    )


def check_paths(feed: str, files: dict[str, str], root: Path = REPO_ROOT) -> None:
    """Refuse anything a generator would never write: a path outside dbt/models/<pack>/, or
    over an existing file that is not generated (a hand-written model is never replaced)."""
    pack, _, _ = names(feed)
    base = (root / "dbt" / "models" / pack).resolve()
    for rel in files:
        target = (root / rel).resolve()
        if not target.is_relative_to(base) or target.suffix not in (".sql", ".yml"):
            raise GenerationError(f"{rel}: generated files live under dbt/models/{pack}/")
        if target.exists() and not _is_generated(target):
            raise GenerationError(f"{rel} exists and is hand-written: not replaced")


def plan_files(c: Contract, root: Path = REPO_ROOT) -> dict[str, str]:
    """The files to write for a contract: none when its feed's models are hand-written or
    its format has no generator; else the rendered files, checked by check_paths."""
    if not (root / "dbt" / "models").is_dir():
        # Without the project every feed would look new: hand-written models would be
        # missed. Refuse rather than generate over them.
        raise GenerationError("the dbt project is not available here")
    if c.format_type not in FORMATS or hand_written(c.feed, root / "dbt" / "models"):
        return {}
    files = render(c)
    check_paths(c.feed, files, root)
    return files


def affected_models(feed: str, removed: list[str], models: Path = DBT_MODELS) -> list[str]:
    """Hand-written models that read a removed or renamed column: the feed's models whose
    SQL reads the column's JSON key (`->> '<column>'`) or selects it by name, then every
    model that ref()s one of them, transitively. A text search over the SQL: dbt's
    manifest knows which models depend on which, not which columns they read."""
    if not removed:
        return []
    sql = {p.stem: p.read_text(encoding="utf-8") for p in models.rglob("*.sql")
           if not _is_generated(p)}  # fmt: skip
    own = {p.stem for p in hand_written(feed, models)}
    reads = re.compile(r"(->>\s*'(" + "|".join(map(re.escape, removed)) + r")')|\b("
                       + "|".join(map(re.escape, removed)) + r")\b")  # fmt: skip
    hit = {m for m in own if reads.search(sql[m])}
    while True:
        refs = re.compile(r"ref\(\s*'(" + "|".join(map(re.escape, hit)) + r")'\s*\)")
        more = {m for m, text in sql.items() if m not in hit and refs.search(text)}
        if not more:
            return sorted(hit)
        hit |= more


def write(files: dict[str, str], root: Path = REPO_ROOT) -> list[str]:
    out = []
    for rel, text in sorted(files.items()):
        target = root / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8", newline="\n")
        out.append(rel)
    return out


def dbt_parse(files: dict[str, str], root: Path = REPO_ROOT, timeout: int = 300) -> dict[str, Any]:
    """`dbt parse` on a temporary copy of the dbt project with the generated files added: it
    compiles every model's Jinja and refs, and connects to no database. Returns
    {"ok": bool, "output": the tail of dbt's output}, or ok None when dbt is not installed."""
    import os
    import shutil
    import subprocess
    import tempfile

    from dip.dbt_runner import dbt_env

    exe = os.environ.get("DIP_DBT_BIN") or shutil.which("dbt")
    if not exe:
        return {"ok": None, "output": "dbt is not installed here"}
    with tempfile.TemporaryDirectory() as tmp:
        project = Path(tmp) / "dbt"
        skip = shutil.ignore_patterns("target", "logs", "dbt_packages")
        shutil.copytree(root / "dbt", project, ignore=skip)
        for rel, text in files.items():
            target = Path(tmp) / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8", newline="\n")
        env = {**dbt_env("postgresql://parse:parse@localhost:5432/parse"),
               "DBT_TARGET_PATH": str(project / "target")}  # fmt: skip
        try:
            out = subprocess.run([exe, "parse", "--project-dir", str(project), "--profiles-dir",
                                  str(project)], env=env, capture_output=True, text=True,
                                 encoding="utf-8", timeout=timeout, check=False)  # fmt: skip
        except subprocess.TimeoutExpired:
            return {"ok": False, "output": f"dbt parse took over {timeout}s"}
    return {"ok": out.returncode == 0, "output": (out.stdout + out.stderr)[-2000:]}
