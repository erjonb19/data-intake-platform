"""dbt models generated from a data contract (Stage 10, S10.3; PLAN.md section 8.12).

    python -m dip contracts dbt FEED [--write]

The contract is the single source of truth: the SQL comes from templates here, never from
a model. For a CSV or Excel feed (both land in bronze.csv_record):

  silver  <pack>_<name>_record: one row per accepted row, every contract column typed by
          its contract type, with the delivery columns every hand-written file-feed model
          has (file_sha256, row_number, source_key, file_date, received_at,
          contract_version) and the same `deliveries` CTE. The intake already checked each
          value, and optional columns go through nullif(..., ''); integers are numeric, so
          no length overflows. (A decimal Python reads and Postgres does not, such as
          `1_000` or non-ASCII digits, would still fail the cast: PLAN.md section 11.)
  tests   _<pack>_<name>.yml: (file_sha256, row_number) unique; not_null for required
          columns; accepted_values for `allowed` (values with quotes, Jinja delimiters or
          backslashes are refused: dbt renders them as Jinja and SQL); a `unique: true`
          string column unique within its file, empties aside (as the intake checks it).
          Column names are quoted in every test.
  gold    <pack>_<name>: only when the contract has a `model:` block. `grain:
          latest_per_key` with `key: [...]` keeps the newest row per key (by file date,
          then receipt); `grain: all_rows` keeps every row as a table.

Files go under dbt/models/<pack>/<name>/ and their first line is the GENERATED header; the
generator rewrites only such files, never in a folder dbt_project.yml configures, and never
under a model name that exists elsewhere. Feeds whose models are hand-written (any model
tagged with the feed that is not generated: eligibility, claims, finance, X12) get no
generated files. For them, `affected_models` lists the hand-written models that read a
column a candidate contract removes or renames, for a person to fix.
"""

from __future__ import annotations

import hashlib
import re
from pathlib import Path
from typing import Any

from dip.contracts import REPO_ROOT, Contract

DBT_MODELS = REPO_ROOT / "dbt" / "models"
GENERATED = "generated by dip from"
FORMATS = ("csv", "excel")
CASTS = {"integer": "numeric", "decimal": "numeric", "date": "date", "boolean": "boolean"}


class GenerationError(ValueError):
    pass


def names(feed: str) -> tuple[str, str, str]:
    """(pack, name, model prefix) for a feed `<pack>.<name>`."""
    pack, _, name = feed.partition(".")
    return pack, name, f"{pack}_{name}"


def paths(feed: str) -> dict[str, str]:
    """Repo-relative paths of the generated files, by role."""
    pack, name, prefix = names(feed)
    base = f"dbt/models/{pack}/{name}"
    return {"silver": f"{base}/{prefix}_record.sql", "tests": f"{base}/_{prefix}.yml",
            "gold": f"{base}/{prefix}.sql"}  # fmt: skip


def _header(c: Contract, comment: str) -> str:
    return (f"{comment} {GENERATED} the {c.feed} contract, version {c.version}. Do not edit:"
            f" change the contract, then\n{comment} python -m dip contracts dbt {c.feed}"
            " --write\n")  # fmt: skip


def _column(col: dict[str, Any]) -> str:
    name, kind = col["name"], col.get("type", "string")
    raw = f"b.record ->> '{name}'"
    value = raw if col.get("required") else f"nullif({raw}, '')"
    if kind in CASTS:
        value = f"({value})::{CASTS[kind]}"
    return f'    {value} as "{name}"'


def _silver(c: Contract) -> str:
    feed = c.feed
    cols = ",\n".join(_column(col) for col in c.spec["columns"])
    return (
        _header(c, "--")
        + "{{ config(schema='silver', materialized='view', tags=['file_feed', '"
        + feed
        + "', 'generated']) }}\n\n"
        f"""-- Silver: every accepted row of every {feed} file, typed by the contract.
with deliveries as (
    select distinct on (d.file_sha256)
        d.file_sha256,
        d.source_key,
        coalesce(d.file_date, (d.received_at at time zone 'UTC')::date) as file_date,
        d.received_at
    from {{{{ source('ops', 'intake_delivery') }}}} as d
    where d.feed = '{feed}'
    order by
        d.file_sha256,
        coalesce(d.file_date, (d.received_at at time zone 'UTC')::date) desc,
        d.received_at desc,
        d.source_key desc
)

select
    b.file_sha256,
    b.row_number,
    d.source_key,
    d.file_date,
    d.received_at,
    f.contract_version,
{cols}
from {{{{ source('bronze', 'csv_record') }}}} as b
inner join {{{{ source('ops', 'intake_file') }}}} as f
    on f.feed = b.feed and f.file_sha256 = b.file_sha256
inner join deliveries as d on d.file_sha256 = b.file_sha256
where b.feed = '{feed}'
"""
    )


def _gold(c: Contract, model: dict[str, Any]) -> str:
    _, _, prefix = names(c.feed)
    head = (_header(c, "--") + "{{ config(schema='gold', materialized='table', tags=["
            f"'file_feed', '{c.feed}', 'generated']) }}}}\n\n")  # fmt: skip
    if model["grain"] == "all_rows":
        return head + (f"-- Gold: every accepted {c.feed} row (grain: all_rows).\n"
                       f"select * from {{{{ ref('{prefix}_record') }}}}\n")  # fmt: skip
    key = ", ".join(f'r."{k}"' for k in model["key"])
    return head + (
        f"-- Gold: the newest row per {', '.join(model['key'])} (grain: latest_per_key), by\n"
        "-- the file's business date, then when it was received.\n"
        f"select distinct on ({key}) r.*\n"
        f"from {{{{ ref('{prefix}_record') }}}} as r\n"
        f"order by {key}, r.file_date desc, r.received_at desc, r.file_sha256 desc,"
        " r.row_number desc\n"
    )


def _tests(c: Contract, model: dict[str, Any] | None) -> str:
    _, _, prefix = names(c.feed)
    lines = [_header(c, "#").rstrip("\n"), "version: 2", "", "models:",
             f"  - name: {prefix}_record", "    data_tests:", "      - unique_combination:",
             "          arguments: {columns: [file_sha256, row_number]}"]  # fmt: skip
    # Per file, as the intake checks it: empties aside, and only for string columns (the
    # intake compares raw text, so 007 and 7 are two values there but one after a cast).
    unique = [col["name"] for col in c.spec["columns"]
              if col.get("unique") and col.get("type", "string") == "string"]  # fmt: skip
    for u in unique:
        lines += ["      - unique_combination:",
                  f"""          arguments: {{columns: [file_sha256, '"{u}"']}}""",
                  f"""          config: {{where: '"{u}" is not null'}}"""]  # fmt: skip
    cols = []
    for col in c.spec["columns"]:
        tests = []
        if col.get("required"):
            tests.append("not_null")
        if col.get("allowed") and col.get("type", "string") == "string":
            values = ", ".join(_yaml_str(v) for v in col["allowed"])
            tests.append(f"accepted_values: {{arguments: {{values: [{values}]}}}}")
        if tests:
            cols += [f"      - name: {col['name']}", "        quote: true", "        data_tests:"]
            cols += [f"          - {t}" for t in tests]
    if cols:
        lines += ["    columns:", *cols]
    if model and model["grain"] == "latest_per_key":
        keys = ", ".join(f"""'"{k}"'""" for k in model["key"])
        lines += [f"  - name: {prefix}", "    data_tests:", "      - unique_combination:",
                  f"          arguments: {{columns: [{keys}]}}"]  # fmt: skip
    return "\n".join(lines) + "\n"


def _yaml_str(v: Any) -> str:
    """A YAML double-quoted scalar for an `allowed` value. Values dbt would render as Jinja
    or splice into SQL unescaped (quotes, Jinja delimiters, backslashes, newlines) are
    refused by render() before this is called."""
    return f'"{v}"'


# dbt renders test arguments as Jinja and accepted_values puts each value in '...' as is.
UNSAFE_VALUE = re.compile(r"""['"\\\n\r\t]|\{[{%#]|[}%#]\}""")
# Columns the silver model adds itself; a contract column of the same name would repeat it.
DELIVERY_COLUMNS = ("file_sha256", "row_number", "source_key", "file_date", "received_at",
                    "contract_version")  # fmt: skip


def render(c: Contract) -> dict[str, str]:
    """The generated files for a contract, as {repo-relative path: text}."""
    if c.format_type not in FORMATS:
        raise GenerationError(f"{c.feed}: no generator for format {c.format_type!r}")
    for col in c.spec["columns"]:
        if col["name"] in DELIVERY_COLUMNS:
            raise GenerationError(f"{c.feed}: column {col['name']!r} is a delivery column")
        bad = [v for v in col.get("allowed") or [] if UNSAFE_VALUE.search(str(v))]
        if bad:
            raise GenerationError(f"{c.feed}: {col['name']}: allowed values with quotes, Jinja"
                                  f" delimiters or backslashes: {bad[:3]}")  # fmt: skip
    model = c.spec.get("model")
    p = paths(c.feed)
    out = {p["silver"]: _silver(c), p["tests"]: _tests(c, model)}
    if model:
        out[p["gold"]] = _gold(c, model)
    return out


def files_sha256(files: dict[str, str]) -> str:
    """One hash over the files and their paths: what a person approved."""
    h = hashlib.sha256()
    for path in sorted(files):
        h.update(path.encode() + b"\0" + files[path].encode() + b"\0")
    return h.hexdigest()


# --- The project's models, read from a tree: the disk, or a commit (write_branch) --------
#
# `models` maps each repo-relative path under dbt/models (.sql and .yml) to its text.


def disk_models(root: Path = REPO_ROOT) -> dict[str, str]:
    base = root / "dbt" / "models"
    if not base.is_dir():
        return {}
    return {p.relative_to(root).as_posix(): p.read_text(encoding="utf-8", errors="replace")
            for p in sorted(base.rglob("*")) if p.suffix in (".sql", ".yml")}  # fmt: skip


def is_generated(text: str) -> bool:
    """Generated files start with the header, on their first line."""
    first = text.lstrip("﻿").split("\n", 1)[0]
    return first.startswith(("-- " + GENERATED, "# " + GENERATED))


def _strip_comments(sql: str) -> str:
    return re.sub(r"--[^\n]*|/\*.*?\*/|\{#.*?#\}", " ", sql, flags=re.S)


def hand_written(feed: str, models: dict[str, str]) -> list[str]:
    """Hand-written models tagged with the feed (in a SQL config or a YAML file), by stem."""
    q = r"""['"]"""
    tag = re.compile(r"tags\s*[=:]\s*\[[^\]]*" + q + re.escape(feed) + q)
    out = set()
    for path, text in models.items():
        if is_generated(text) or not tag.search(text):
            continue
        if path.endswith(".sql"):
            out.add(Path(path).stem)
        else:  # a YAML file that tags its models: those models
            out |= {Path(p).stem for p in models if p.endswith(".sql")
                    and Path(p).parent == Path(path).parent}  # fmt: skip
    return sorted(out)


def reserved_folders(root: Path = REPO_ROOT) -> set[str]:
    """Folders under dbt/models that dbt_project.yml configures (silver, shareable, ...):
    a pack of that name would inherit their settings, so none is generated there."""
    import yaml

    try:
        spec = yaml.safe_load((root / "dbt" / "dbt_project.yml").read_text(encoding="utf-8"))
    except OSError:
        return set()
    return {k for k in ((spec.get("models") or {}).get("dip") or {}) if not k.startswith("+")}


def check_paths(feed: str, files: dict[str, str], models: dict[str, str],
                root: Path = REPO_ROOT) -> None:  # fmt: skip
    """Refuse anything a generator would never write: a path outside dbt/models/<pack>/, a
    file over an existing one that is not generated, or a model name another model has."""
    pack, _, _ = names(feed)
    if pack in reserved_folders(root):
        raise GenerationError(f"dbt/models/{pack}/ is configured by dbt_project.yml")
    base = (root / "dbt" / "models" / pack).resolve()
    stems = {}
    for path in models:
        if path.endswith(".sql"):
            stems.setdefault(Path(path).stem, []).append(path)
    for rel in files:
        target = (root / rel).resolve()
        if not target.is_relative_to(base) or target.suffix not in (".sql", ".yml"):
            raise GenerationError(f"{rel}: generated files live under dbt/models/{pack}/")
        if rel in models and not is_generated(models[rel]):
            raise GenerationError(f"{rel} exists and is hand-written: not replaced")
        if rel.endswith(".sql") and any(p != rel for p in stems.get(Path(rel).stem, [])):
            raise GenerationError(f"model {Path(rel).stem} already exists elsewhere")


def stale_files(feed: str, files: dict[str, str], models: dict[str, str]) -> list[str]:
    """Generated files in the feed's folder that the contract no longer produces (the gold
    model, when the `model:` block is removed): removed with the change."""
    folder = str(Path(paths(feed)["silver"]).parent.as_posix()) + "/"
    return sorted(p for p, text in models.items()
                  if p.startswith(folder) and p not in files and is_generated(text))  # fmt: skip


def plan_files(c: Contract, root: Path = REPO_ROOT,
               models: dict[str, str] | None = None) -> dict[str, str]:  # fmt: skip
    """The files to write for a contract, checked against `models` (default: the disk):
    none when its feed's models are hand-written or its format has no generator."""
    if models is None:
        if not (root / "dbt" / "models").is_dir():
            # Without the project every feed would look new: hand-written models would be
            # missed. Refuse rather than generate over them.
            raise GenerationError("the dbt project is not available here")
        models = disk_models(root)
    if c.format_type not in FORMATS or hand_written(c.feed, models):
        return {}
    files = render(c)
    check_paths(c.feed, files, models, root)
    return files


def affected_models(feed: str, removed: list[str], models: dict[str, str]) -> list[str]:
    """Hand-written models that read a removed or renamed column: the feed's models (hand-
    written or generated) whose SQL, comments stripped, reads the column (`->> 'col'`,
    `"col"`, or the bare name), then every model that ref()s one of them, transitively.
    Only hand-written models are listed: generated ones are regenerated. A text search: dbt's
    manifest knows which models depend on which, not which columns they read."""
    if not removed:
        return []
    sql = {Path(p).stem: _strip_comments(t) for p, t in models.items() if p.endswith(".sql")}
    generated = {Path(p).stem for p, t in models.items() if p.endswith(".sql") and is_generated(t)}
    q = r"""['"]"""
    tag = re.compile(r"tags\s*[=:]\s*\[[^\]]*" + q + re.escape(feed) + q)
    own = {m for m, text in sql.items() if tag.search(text) or m in generated
           and m.startswith(names(feed)[2])}  # fmt: skip
    cols = "|".join(map(re.escape, removed))
    reads = re.compile(r"->>\s*'(" + cols + r")'|\"(" + cols + r")\"|\b(" + cols + r")\b")
    hit = {m for m in own if reads.search(sql[m])}
    while hit:
        refs = re.compile(r"ref\(\s*" + q + "(" + "|".join(map(re.escape, hit)) + ")" + q)
        more = {m for m, text in sql.items() if m not in hit and refs.search(text)}
        if not more:
            break
        hit |= more
    return sorted(hit - generated)


def write(files: dict[str, str], root: Path = REPO_ROOT) -> list[str]:
    out = []
    for rel, text in sorted(files.items()):
        target = root / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8", newline="\n")
        out.append(rel)
    return out


def dbt_parse(files: dict[str, str], root: Path = REPO_ROOT, timeout: int = 120) -> dict[str, Any]:
    """`dbt parse` on a temporary copy of the dbt project with the generated files added: it
    compiles every model's Jinja and refs, and connects to no database. dbt gets a minimal
    environment (no model or MCP keys), so nothing it prints can carry a secret. Returns
    {"ok": bool, "output": the tail of dbt's output}, or ok None when dbt is not installed."""
    import os
    import shutil
    import subprocess
    import tempfile

    exe = os.environ.get("DIP_DBT_BIN") or shutil.which("dbt")
    if not exe:
        return {"ok": None, "output": "dbt is not installed here"}
    keep = ("PATH", "SYSTEMROOT", "TEMP", "TMP", "HOME", "USERPROFILE", "LANG", "PYTHONPATH")
    with tempfile.TemporaryDirectory() as tmp:
        project = Path(tmp) / "dbt"
        skip = shutil.ignore_patterns("target", "logs", "dbt_packages")
        shutil.copytree(root / "dbt", project, ignore=skip)
        for rel, text in files.items():
            target = Path(tmp) / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8", newline="\n")
        env = {k: os.environ[k] for k in keep if k in os.environ} | {
            "DIP_PG_HOST": "localhost", "DIP_PG_PORT": "5432", "DIP_PG_USER": "parse",
            "DIP_PG_PASSWORD": "parse", "DIP_PG_DB": "parse",
            "DBT_SEND_ANONYMOUS_USAGE_STATS": "false", "PYTHONIOENCODING": "utf-8",
            "DBT_TARGET_PATH": str(project / "target"),
        }  # fmt: skip
        try:
            out = subprocess.run([exe, "parse", "--project-dir", str(project), "--profiles-dir",
                                  str(project)], env=env, capture_output=True, text=True,
                                 encoding="utf-8", timeout=timeout, check=False)  # fmt: skip
        except subprocess.TimeoutExpired:
            return {"ok": False, "output": f"dbt parse took over {timeout}s"}
    return {"ok": out.returncode == 0, "output": (out.stdout + out.stderr)[-2000:]}
