"""dbt models generated from a contract (Stage 10, S10.3; dip/dbt_gen.py): golden files,
what is never generated or overwritten, the hand-written models a removed column affects,
and the branch an approved proposal writes."""

from __future__ import annotations

import os
import subprocess
from pathlib import Path

import pytest

from dip import dbt_gen
from dip.contracts import REPO_ROOT, ContractError, load_contracts, parse_contract

FIXTURES = Path(__file__).resolve().parents[1] / "fixtures" / "dbt_gen"
GOLDEN = FIXTURES / "golden"
REFERENCE = REPO_ROOT / "agents" / "evals" / "contract_author" / "reference"
CONTRACTS = [FIXTURES / "purchase_orders.yaml", *sorted(REFERENCE.glob("*.yaml"))]


def _contract(path: Path):
    return parse_contract(path.read_text(encoding="utf-8"), path)


@pytest.mark.parametrize("path", CONTRACTS, ids=lambda p: p.stem)
def test_the_generated_files_match_the_golden_ones(path):
    """Byte for byte. After a deliberate template change: DIP_UPDATE_GOLDEN=1 pytest ..."""
    files = dbt_gen.render(_contract(path))
    for rel, text in files.items():
        golden = GOLDEN / Path(rel).relative_to("dbt/models")
        if os.environ.get("DIP_UPDATE_GOLDEN"):
            golden.parent.mkdir(parents=True, exist_ok=True)
            golden.write_text(text, encoding="utf-8", newline="\n")
        assert golden.read_text(encoding="utf-8") == text, rel


def test_every_column_is_typed_and_optional_ones_go_through_nullif():
    sql = dbt_gen.render(_contract(FIXTURES / "purchase_orders.yaml"))[
        "dbt/models/finance/purchase_orders/finance_purchase_orders_record.sql"
    ]
    assert "(b.record ->> 'line')::numeric as \"line\"" in sql  # numeric: no overflow
    assert "(b.record ->> 'amount')::numeric as \"amount\"" in sql
    assert "(b.record ->> 'approved')::boolean as \"approved\"" in sql
    assert "nullif(b.record ->> 'note', '') as \"note\"" in sql
    assert "(nullif(b.record ->> 'due_date', ''))::date as \"due_date\"" in sql
    assert sql.startswith("-- generated by dip from the finance.purchase_orders contract")


def test_feeds_with_hand_written_models_get_no_generated_files():
    contracts = load_contracts()
    models = dbt_gen.disk_models()
    for feed in ("healthcare.eligibility", "healthcare.claims", "finance.vendor_invoice"):
        assert dbt_gen.hand_written(feed, models), feed
        assert dbt_gen.plan_files(contracts[feed]) == {}
    # PDF and X12 feeds have no generator either.
    assert dbt_gen.plan_files(contracts["healthcare.claims_837"]) == {}
    with pytest.raises(dbt_gen.GenerationError, match="no generator"):
        dbt_gen.render(contracts["finance.vendor_invoice_pdf"])


def test_a_removed_or_renamed_column_lists_the_hand_written_models_that_read_it():
    models = dbt_gen.disk_models()
    got = dbt_gen.affected_models("healthcare.eligibility", ["plan_code"], models)
    assert {"eligibility_record", "member_eligibility"} <= set(got)
    assert dbt_gen.affected_models("healthcare.eligibility", [], models) == []
    assert dbt_gen.affected_models("healthcare.eligibility", ["no_such_column"], models) == []
    # A column named only in a comment does not count.
    fake = {"dbt/models/x/a.sql": "{{ config(tags=['f.x']) }}\n-- plan_code was here\nselect 1",
            "dbt/models/x/b.sql": "select * from {{ ref(\"a\") }}"}  # fmt: skip
    assert dbt_gen.affected_models("f.x", ["plan_code"], fake) == []
    fake["dbt/models/x/a.sql"] += " as plan_code"
    assert dbt_gen.affected_models("f.x", ["plan_code"], fake) == ["a", "b"]  # and its child


def test_paths_outside_the_pack_and_hand_written_files_are_refused():
    feed, models = "healthcare.eligibility", dbt_gen.disk_models()
    with pytest.raises(dbt_gen.GenerationError, match="live under dbt/models/healthcare"):
        dbt_gen.check_paths(feed, {"dags/evil.sql": "x"}, models)
    with pytest.raises(dbt_gen.GenerationError, match="live under"):
        dbt_gen.check_paths(feed, {"dbt/models/healthcare/../../../x.sql": "x"}, models)
    with pytest.raises(dbt_gen.GenerationError, match="hand-written"):
        dbt_gen.check_paths("finance.x", {"dbt/models/finance/vendor_invoice.sql": "x"}, models)
    # A model name that exists elsewhere (mimic.patient -> mimic_patient), or a pack named
    # after a folder dbt_project.yml configures: refused.
    with pytest.raises(dbt_gen.GenerationError, match="already exists"):
        dbt_gen.check_paths("mimic.x", {"dbt/models/mimic/x/mimic_patient.sql": "x"}, models)
    with pytest.raises(dbt_gen.GenerationError, match="configured by dbt_project"):
        dbt_gen.check_paths("silver.x", {"dbt/models/silver/x/silver_x_record.sql": "x"}, models)


def test_values_dbt_would_render_as_jinja_or_sql_are_refused():
    text = (FIXTURES / "purchase_orders.yaml").read_text(encoding="utf-8")
    p = FIXTURES / "purchase_orders.yaml"
    for bad in ("\"{{ env_var('X') }}\"", '"O\'Brien"', '"{% if x %}"'):
        c = parse_contract(text.replace("allowed: [USD, EUR]", f"allowed: [USD, {bad}]"), p)
        with pytest.raises(dbt_gen.GenerationError, match="allowed values"):
            dbt_gen.render(c)
    c = parse_contract(text.replace("name: note,", "name: file_date,"), p)
    with pytest.raises(dbt_gen.GenerationError, match="delivery column"):
        dbt_gen.render(c)


def test_only_a_first_line_header_marks_a_file_generated():
    assert dbt_gen.is_generated("-- generated by dip from the x contract\nselect 1")
    assert not dbt_gen.is_generated("select 1 -- generated by dip from nothing")
    assert not dbt_gen.is_generated("-- note\n-- generated by dip from the x contract")


def test_stale_generated_files_are_listed_for_removal():
    c = _contract(FIXTURES / "purchase_orders.yaml")
    files = dbt_gen.render(c)
    gold = "dbt/models/finance/purchase_orders/finance_purchase_orders.sql"
    without = {k: v for k, v in files.items() if k != gold}
    assert dbt_gen.stale_files(c.feed, without, files) == [gold]


def test_without_the_dbt_project_nothing_is_generated(tmp_path):
    """An image without the project would see every feed as new; it must refuse instead."""
    with pytest.raises(dbt_gen.GenerationError, match="not available"):
        dbt_gen.plan_files(_contract(FIXTURES / "purchase_orders.yaml"), tmp_path)


def test_the_model_block_is_checked(tmp_path):
    text = (FIXTURES / "purchase_orders.yaml").read_text(encoding="utf-8")
    p = tmp_path / "po.yaml"
    for bad, why in (("key: [po_number, line]", "key: [nope]"),
                     ("grain: latest_per_key, key: [po_number, line]", "grain: latest_per_key"),
                     ("grain: latest_per_key, key: [po_number, line]",
                      "grain: all_rows, key: [po_number]")):  # fmt: skip
        with pytest.raises(ContractError, match="model"):
            parse_contract(text.replace(bad, why), p)


def _git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True,
                          check=True).stdout.strip()  # fmt: skip


def test_an_approved_new_feed_branch_holds_the_contract_and_its_models(tmp_path, monkeypatch):
    from dip.agents.contract_pr import write_branch

    repo = tmp_path / "repo"
    (repo / "packs/finance/contracts").mkdir(parents=True)
    (repo / "dbt/models/finance").mkdir(parents=True)
    (repo / "dbt/models/finance/vendor_invoice.sql").write_text(
        "{{ config(tags=['file_feed', 'finance.vendor_invoice']) }}\nselect 1\n", "utf-8"
    )
    _git(repo, "init", "-q", "-b", "main")
    for who in ("AUTHOR", "COMMITTER"):
        monkeypatch.setenv(f"GIT_{who}_NAME", "t")
        monkeypatch.setenv(f"GIT_{who}_EMAIL", "t@example.com")
    _git(repo, "add", "-A")
    _git(repo, "commit", "-qm", "base")
    text = (FIXTURES / "purchase_orders.yaml").read_text(encoding="utf-8")
    c = parse_contract(text, repo / "packs/finance/contracts/purchase_orders.yaml")
    files = dbt_gen.plan_files(c, repo)
    rel = "packs/finance/contracts/purchase_orders.yaml"
    payload = {"feed": c.feed, "mode": "onboard", "path": rel, "base_sha256": None,
               "contract_yaml": text, "rationale": "new vendor",
               "validation": {}, "loosening": [], "dbt_files": files,
               "dbt_files_sha256": dbt_gen.files_sha256(files), "dbt_affected": []}  # fmt: skip
    got = write_branch(payload, 3, "human:tester", root=repo)
    tree = _git(repo, "ls-tree", "--name-only", "-r", got["branch"]).splitlines()
    assert payload["path"] in tree and set(files) <= set(tree) and len(got["dbt_files"]) == 3
    # The files on the branch are rendered from the approved contract, not read from the
    # payload: a payload whose files differ from what the contract renders is refused.
    tampered = {**payload, "dbt_files_sha256": "0" * 64}
    with pytest.raises(RuntimeError, match="differ from the ones approved"):
        write_branch(tampered, 4, "human:tester", root=repo)


def test_the_branch_is_checked_against_main_not_the_checkout(tmp_path, monkeypatch):
    """A hand-written model for the feed exists on main but not in the person's checkout:
    the generated files would replace it, so the branch is refused."""
    from dip.agents.contract_pr import write_branch

    repo = tmp_path / "repo"
    (repo / "packs/finance/contracts").mkdir(parents=True)
    (repo / "dbt/models/finance").mkdir(parents=True)
    (repo / "dbt/models/finance/po.sql").write_text(
        "{{ config(tags=['file_feed', 'finance.purchase_orders']) }}\nselect 1\n", "utf-8"
    )
    _git(repo, "init", "-q", "-b", "main")
    for who in ("AUTHOR", "COMMITTER"):
        monkeypatch.setenv(f"GIT_{who}_NAME", "t")
        monkeypatch.setenv(f"GIT_{who}_EMAIL", "t@example.com")
    _git(repo, "add", "-A")
    _git(repo, "commit", "-qm", "base")
    _git(repo, "checkout", "-q", "-b", "other")
    _git(repo, "rm", "-q", "dbt/models/finance/po.sql")
    _git(repo, "commit", "-qm", "not on main")
    text = (FIXTURES / "purchase_orders.yaml").read_text(encoding="utf-8")
    c = parse_contract(text, repo / "packs/finance/contracts/purchase_orders.yaml")
    files = dbt_gen.render(c)  # as the checkout (no models at all) would have it
    assert files
    payload = {"feed": c.feed, "mode": "onboard", "base_sha256": None,
               "path": "packs/finance/contracts/purchase_orders.yaml", "contract_yaml": text,
               "rationale": "r", "validation": {}, "loosening": [], "dbt_files": files,
               "dbt_files_sha256": dbt_gen.files_sha256(files)}  # fmt: skip
    with pytest.raises(RuntimeError, match="differ from the ones approved"):
        write_branch(payload, 5, "human:tester", root=repo)
